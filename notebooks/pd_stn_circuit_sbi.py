def ood_report(X_emp, X_sim, names, return_flags=False):
    Xs = X_sim[np.isfinite(X_sim).all(1)]; mu = Xs.mean(0); icov = np.linalg.pinv(np.cov(Xs.T))
    md = lambda X: np.sqrt(np.einsum("ij,jk,ik->i", X - mu, icov, X - mu))
    thr = np.percentile(md(Xs), 99)
    pct = np.array([[stats.percentileofscore(Xs[:, j], v) if np.isfinite(v) else np.nan for j, v in enumerate(x)] for x in X_emp])
    rep = pd.DataFrame(dict(stat=names, frac_outside=np.nanmean((pct < 0.5) | (pct > 99.5), 0), median_pct=np.nanmedian(pct, 0)))
    d = md(np.nan_to_num(X_emp)); print(f"Mahalanobis: {np.mean(d > thr):.0%} of recordings beyond the simulations' 99th percentile")
    rep = rep.sort_values("frac_outside", ascending=False)
    return (rep, d > thr) if return_flags else rep


