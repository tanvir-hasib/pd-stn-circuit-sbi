def classify_channels(titles):
    lfp, eeg, other = [], [], []
    for i, t in enumerate(titles):
        tl = t.strip().lower()
        if OX_LFP_REGEX is not None:
            ok = re.search(OX_LFP_REGEX, t.strip()) and (len(set(re.findall(r"\d", t))) == 2)
            if not ok and OX_ALLOW_FALLBACK and OX_MONO_REGEX:
                ok = bool(re.search(OX_MONO_REGEX, t.strip()))
            (lfp if ok else (eeg if tl in EEG_1020 else other)).append(i); continue
        toks = re.split(r"[\s_\-:/]+", tl)
