def simulate_stats(theta, seed, ref=None):
    """θ (n, 12) → summary statistics, simulated batch by batch."""
    theta = np.atleast_2d(theta); out = []
    T = PIPE["seg_len"] + 2.0
    for s in range(0, len(theta), BATCH):
        th = theta[s:s + BATCH]
        rec = simulate_circuit(theta_to_sim(th), T, seed=seed + s, verbose=True)
