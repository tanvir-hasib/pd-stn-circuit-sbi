def stim_mask(X, fs0, win=2.0):
    """Per-window flag of DBS/stimulation: a narrow spectral line in 110-270 Hz (not a 50-Hz harmonic) that stands
    OX_STIM_DB above the median of its +-10 Hz neighbourhood, on any channel. Returns a boolean per-sample 'clean' mask."""
    n = int(win * fs0); nw = X.shape[1] // n
    if nw < 1:
        return np.ones(X.shape[1], bool), 0.0
    seg = X[:, :nw * n].reshape(len(X), nw, n)
    seg = seg - seg.mean(-1, keepdims=True)
    P = np.abs(np.fft.rfft(seg * np.hanning(n), axis=-1)) ** 2
    f = np.fft.rfftfreq(n, 1 / fs0); df = f[1]
    band = np.where((f >= 110) & (f <= 270) & (np.min(np.abs(f[:, None] - OX_LINE_FREQ * np.arange(1, 7)), 1) > 2.0))[0]
    k = int(10 / df)
    lP = np.log10(P + 1e-30)
    prom = np.full(P.shape[:2], -np.inf)
    for b in band:
        nb = np.r_[max(0, b - k):max(0, b - 2), b + 3:min(len(f), b + k + 1)]
        prom = np.maximum(prom, 10 * (lP[..., b] - np.median(lP[..., nb], -1)))
    raw = (prom > OX_STIM_DB).any(0)
    # stimulation lasts many seconds: keep runs of >= 3 consecutive flagged windows, dilated by one window
    run = np.convolve(raw.astype(int), np.ones(3, int), "same") >= 3
    run = np.convolve(run.astype(int), np.ones(5, int), "same") > 0
    bad = run & (np.convolve(raw.astype(int), np.ones(3, int), "same") > 0)
    bad = np.convolve(bad.astype(int), np.ones(3, int), "same") > 0
    clean = np.repeat(~bad, n)
    clean = np.r_[clean, np.full(X.shape[1] - len(clean), clean[-1] if len(clean) else True)]
    return clean, bad.mean()


def first_clean_stretch(clean, fs0, need_s, max_s, policy="prestim", gap_s=60.0):
    """Analysis stretch of >= need_s stimulation-free data, cropped to max_s.
    'prestim': must lie before the first stimulation block. 'gap': otherwise the first run starting >= gap_s after a block.
    Returns (start, stop, kind, first_stim_s) or None."""
    d = np.diff(np.r_[0, clean.astype(int), 0]); st, en = np.where(d == 1)[0], np.where(d == -1)[0]
    bad = np.where(~clean)[0]; first = bad[0] if len(bad) else None
    fs_first = None if first is None else first / fs0
    if first is None or first >= need_s * fs0:
        stop = len(clean) if first is None else first
        return 0, min(stop, int(max_s * fs0)), "prestim", fs_first
    if policy == "gap":
        for a_, b_ in zip(st, en):
            a2 = a_ + (int(gap_s * fs0) if a_ > 0 else 0)
            if (b_ - a2) >= need_s * fs0:
                return a2, min(b_, a2 + int(max_s * fs0)), "poststim", fs_first
    return None


def ox_preprocess(X, fs0, extra_notch=()):
    """Notch 50-Hz harmonics (+ extra) at the original rate, then resample to PIPE['fs'] (polyphase)."""
    fr = [OX_LINE_FREQ * k for k in range(1, 20) if OX_LINE_FREQ * k < min(fs0 / 2 - 1, 460)] + [e for e in extra_notch if e < fs0 / 2 - 1]
    sos = np.concatenate([signal.tf2sos(*signal.iirnotch(f0, f0 / 1.0, fs0)) for f0 in fr])
    X = signal.sosfiltfilt(sos, X, axis=-1)
    q = Fraction(PIPE["fs"] / fs0).limit_denominator(1000)
    return signal.resample_poly(X, q.numerator, q.denominator, axis=-1)


def best_window(x, L, fs_, aband):
    """Start index of the L-sample window with the fewest transients (5-s steps)."""
    w = transient_mask(x, aband, fs_)
    starts = np.arange(0, len(x) - L + 1, int(5 * fs_))
    if not len(starts):
        return None, w
    bad = np.array([1 - w[s0:s0 + L].mean() for s0 in starts])
    return int(starts[np.argmin(bad)]), w


