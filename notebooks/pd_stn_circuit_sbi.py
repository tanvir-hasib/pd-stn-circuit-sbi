# ## 10.8 Does the HFO prediction need the β-state gate?
#
# v5's joint posterior explains levodopa's HFO increase without an HFO change of its own (Δa_H, Δf_H ≈ 0), via the
# β-state gate (κ_H, ν_H). But κ_H and ν_H are not identifiable (recovery R² ≈ 0), so the explanation could rest on
# the prior. This section re-simulates the §10.7 posterior draws three ways, with **identical circuit runs and noise**
# (one circuit simulation per session; only the HFO generator differs):
#
# * **gated** — as fitted;
# * **frozen gate** — E_β(t) replaced in BOTH sessions by the OFF session's mean β state (geometric mean). The OFF HFO
#   level is unchanged, but the ON HFO no longer follows the ON β state: any predicted HFO change must come from
#   Δa_H, Δf_H or the circuit's spiking (λ_H·S);
# * **no gate** — κ_H = ν_H = 0 (a simpler but cruder ablation: also changes the OFF HFO level).
#
# If the predicted HFO change and its fit to the data (coverage, ρ, MAE) collapse under the frozen gate, the HFO
# increase is explained by the β change through the gate. Also reported: the posterior of κ_H, ν_H (cohort mean vs
# prior), and how the predicted HFO change depends on κ_H across draws.

