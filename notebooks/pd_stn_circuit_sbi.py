def joint_group_table(SUM, Ssamp, label, seed=0):
    """Group-level Δ: per-hemisphere posteriors combined by averaging one draw per hemisphere (posterior of the
    cohort-mean change, hemispheres independent), plus counts of confident hemispheres."""
    rng = np.random.default_rng(seed)
    S = np.stack([s_[rng.integers(0, len(s_), 4000), len(JP):] for s_ in Ssamp])      # (H, 4000, P)
    G = S.mean(0)
    rows = []
    for k, p in enumerate(JP):
        kind = JOINT[p][0]
        fmt = (lambda v: f"×{np.exp(v):.2f}") if kind == "log" else (lambda v: f"{v:+.3g}")
        med = SUM[f"med_{p}"]
        rows.append(dict(param=p, group_mean=fmt(np.median(G[:, k])),
                         ci90=f"[{fmt(np.percentile(G[:, k], 5))}, {fmt(np.percentile(G[:, k], 95))}]",
                         P_group_dec=(G[:, k] < 0).mean(),
                         median_Pdec=SUM[f"Pdec_{p}"].median(), median_Pinc=SUM[f"Pinc_{p}"].median(),
                         n_dec_gt_0_9=int((SUM[f"Pdec_{p}"] > 0.9).sum()), n_inc_gt_0_9=int((SUM[f"Pinc_{p}"] > 0.9).sum()),
                         p_wilcoxon=stats.wilcoxon(med).pvalue if len(med) > 5 else np.nan))
    T = pd.DataFrame(rows)
    print(f"[{label}] joint OFF/ON posterior over {len(Ssamp)} hemispheres (gains as ON/OFF factor; "
          f"prior P(dec) = {J_PRIOR_DEC:.3f} per hemisphere, prior P(group mean < 0) = 0.5):")
    print(T.round(3).to_string(index=False))
    return T


