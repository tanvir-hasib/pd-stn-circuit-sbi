# | label | OFF → ON |
# |---|---|
# | H_HFO | HFO frequency + 20–80 Hz and power × 1.2–2.5 (slow → fast HFO) |
# | H_lock | β-locking λ × 0.1–0.6 |
# | H_GS_HFO | GPe→STN × 0.3–0.8 **and** HFO shift: levodopa reshapes both rhythms, coupling untouched |
