# ## 3. Observation model and summary statistics
#
# **LFP (bipolar STN)** = u_S/U_REF + HFO + w_TS·low-frequency component + aperiodic background of fixed size
# 10^(−SNR_S/20) (exponent χ_S) + white floor (fl_S, relative to the background). **v5 circuit-gated HFO:**
# narrowband (±25 Hz) carrier with amplitude a_H·E_β^(−κ_H)·(1 + λ·tanh z(S)) and instantaneous frequency
# f_H − ν_H·ln E_β, E_β = slow β envelope of u_S / B_REF.
# **MEG (gradiometer over the coherent cortical site)** = u_E/U_REF + w_α·α(f_α) + g_C·z(√E · white) + background
# (χ_C, SNR_C) + white floor (fl_C). √rate·white is the spiking surrogate: broadband, variance ∝ rate. Both
# simulated signals then pass through the same notch filters as the data; notched bins (±2 Hz) are excluded
# from every spectral statistic.
#
# Statistics per site (STN, MEG): aperiodic exponent, mid/high slopes, flattened β and α power, β peak
# frequency/height, β burst rate/duration, envelope CV, waveform sharpness/rise–decay, β→HFA PAC
# (z, log nMVL, cos/sin preferred phase, log Tort MI). Cross-site: β coherence, |imaginary coherence|,
# β phase-slope delay (sign = who leads), β envelope correlation, and **cross-site PAC** (STN β phase →
# cortical HFA, cortical β phase → STN HFA), which separate thalamocortical from hyperdirect routes.

