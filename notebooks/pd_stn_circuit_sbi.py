# %% [markdown]
# ## 10.6 Joint OFF/ON network: which parameters does levodopa change?
#
# The classifier (§6, §10.4) compares 12 discrete hypotheses; the single-session posteriors (§10.2b) fit OFF
# and ON independently. Neither directly asks *how much each parameter changes in the same hemisphere*. This
# network does: it sees OFF and ON together, x = [S_OFF, S_ON − S_OFF], and returns the joint posterior of
# θ_OFF and Δθ for 11 candidate parameters.
#
# **Change prior (neutral, sparse, two-sided).** Every candidate parameter independently changes with
# probability 0.5; if it changes, Δ ~ U(−w, +w) (log-ratio for gains, additive otherwise); if not, Δ ~ N(0, 0.02w).
# Increases and decreases are equally likely a priori, so P(Δ < 0) is not pushed in either direction, and all
# parameters can change at once, so the network must disentangle them. P(decrease) is P(Δ < −ε) with ε = 0.1·w;
# the prior value is 0.225. Session nuisance (SNR, low-frequency component, α) is the same as in §6, and the
# aperiodic exponent χ_S is a candidate too (aperiodic steepening ON levodopa, Wiest et al. 2023).
#
# OFF simulations are the §4 bank (already simulated); only the ON partner of each is new.
#
# **Validation before data:** (a) held-out pairs (recovery R², 90% coverage, AUC of P(decrease));
# (b) attribution on the §6 hypothesis pairs: does an H_NOISE pair get blamed on w_GS?
# (c) posterior predictive check: θ_OFF and Δθ drawn from the posteriors must reproduce the observed OFF→ON
# changes better than a no-mechanism null (nuisance changes only).

# %%
JOINT = {   # name: (kind, slab half-width w); "log" = log-ratio ln(ON/OFF), "add" = ON − OFF
    "w_GS": ("log", 0.9), "sig_slow": ("log", 0.9), "log10_sig": ("add", 0.3), "w_CS": ("log", 0.9),
    "w_TC": ("log", 0.9), "g_ctx": ("log", 0.4), "k_d": ("log", 0.15), "log10_aH": ("add", 0.5),
    "f_H": ("add", 80.0), "lam_H": ("log", 0.9), "chi_S": ("add", 0.5)}
JP = list(JOINT); JIX = [IX[p] for p in JP]
J_EPS = np.array([0.1 * JOINT[p][1] for p in JP])
J_PCHANGE, J_SPIKE = 0.5, 0.02
J_TAG = "j1v5"
J_N = (2 * BATCH - N_RECOVERY) if QUICK else (JOINT_BATCHES * BATCH - N_RECOVERY)


def joint_perturb(th_off, rng):
    """θ_ON from θ_OFF under the neutral sparse change prior + session nuisance. Returns θ_ON and realised Δ."""
    th = th_off.copy(); n = len(th)
    for p in JP:
        kind, w = JOINT[p]; j = IX[p]
        ch = rng.random(n) < J_PCHANGE
        d = np.where(ch, rng.uniform(-w, w, n), rng.normal(0, J_SPIKE * w, n))
        th[:, j] = th[:, j] * np.exp(d) if kind == "log" else th[:, j] + d
    th[:, IX["snr_S"]] += rng.normal(0, 1.5, n); th[:, IX["snr_C"]] += rng.normal(0, 1.5, n)
    th[:, IX["f_T"]] += rng.normal(0, 1.0, n); th[:, IX["bw_T"]] *= np.exp(rng.normal(0, 0.3, n))
    th[:, IX["w_TS"]] *= np.exp(rng.normal(0, 0.4, n)); th[:, IX["w_TM"]] *= np.exp(rng.normal(0, 0.4, n))
    th[:, IX["f_a"]] += rng.normal(0, 0.5, n); th[:, IX["w_a"]] *= np.exp(rng.normal(0, 0.2, n))
    th = np.clip(th, PRIOR_LO, PRIOR_HI)
    return th, realised_delta(th_off, th)


def realised_delta(th_off, th_on):
    D = np.empty((len(th_off), len(JP)))
    for k, p in enumerate(JP):
        j = IX[p]
        D[:, k] = (np.log(np.maximum(th_on[:, j], 1e-9) / np.maximum(th_off[:, j], 1e-9)) if JOINT[p][0] == "log"
                   else th_on[:, j] - th_off[:, j])
    return D


def apply_delta(th_off, D):
    th = th_off.copy()
    for k, p in enumerate(JP):
        j = IX[p]
        th[:, j] = th[:, j] * np.exp(D[:, k]) if JOINT[p][0] == "log" else th[:, j] + D[:, k]
    return np.clip(th, PRIOR_LO, PRIOR_HI)


