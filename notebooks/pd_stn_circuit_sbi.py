def make_joint_npe(phi, F, tag, seed=0):
    fn = OUT_DIR / f"jnpe_{tag}_{len(phi)}_{config_hash()}_{J_TAG}_s{seed}.pt"
    if fn.exists():
        print(f"loaded {fn.name}"); return torch.load(fn, weights_only=False)
    from sbi.utils import BoxUniform
    try:
        from sbi.inference import NPE
    except ImportError:
        from sbi.inference import SNPE as NPE
    torch.manual_seed(seed)
    good = np.isfinite(F).all(1) & np.isfinite(phi).all(1)
    prior = BoxUniform(torch.tensor(J_LO, dtype=torch.float32), torch.tensor(J_HI, dtype=torch.float32))
    inf = NPE(prior=prior, density_estimator="nsf")
    inf.append_simulations(torch.tensor(phi[good], dtype=torch.float32), torch.tensor(F[good], dtype=torch.float32))
    t0 = time.time(); post = inf.build_posterior(inf.train(show_train_summary=False))
    print(f"  joint network '{tag}' trained on {good.sum()} pairs ({(time.time() - t0) / 60:.1f} min)")
    try:
        torch.save(post, fn)
    except Exception as e:
        warnings.warn(f"could not cache ({e})")
    return post


def joint_samples(post, x, n=2000, max_draws=200_000, chunk=20_000):
    xt = torch.tensor(np.asarray(x, float), dtype=torch.float32); keep, drawn = [], 0
    while drawn < max_draws:
        m = min(chunk, max_draws - drawn) if drawn else max(n, 2000)
        s = post.sample((m,), x=xt, show_progress_bars=False, reject_outside_prior=False).detach().cpu().numpy(); drawn += m
        keep.append(s[((s >= J_LO) & (s <= J_HI)).all(1)])
        if sum(len(k) for k in keep) >= n:
            break
    inside = np.concatenate(keep)
    return inside[:n] if len(inside) >= 50 else np.clip(s[:n], J_LO, J_HI)


def joint_summary(s):
    """Per-parameter posterior summary of Δ from joint samples s (n, 2·len(JP))."""
    D = s[:, len(JP):]
    out = {}
    for k, p in enumerate(JP):
        d = D[:, k]; pdec = (d < -J_EPS[k]).mean(); pinc = (d > J_EPS[k]).mean()
        out.update({f"med_{p}": np.median(d), f"lo_{p}": np.percentile(d, 5), f"hi_{p}": np.percentile(d, 95),
                    f"Pdec_{p}": pdec, f"Pinc_{p}": pinc, f"Pnull_{p}": 1 - pdec - pinc})
    return out


