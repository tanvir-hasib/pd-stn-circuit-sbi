def bandpass(x, lo, hi, fs, order=None):
    sos = signal.butter(PIPE["filter_order"] if order is None else order, [lo, hi], btype="band", fs=fs, output="sos")
    return signal.sosfiltfilt(sos, x, axis=-1)


def zs(x):
    x = np.asarray(x, float)
    return (x - x.mean(-1, keepdims=True)) / (x.std(-1, keepdims=True) + 1e-12)


def shaped_noise(n, N, fs, rng, chi=None, peak=None, bw=1.5):
    """Unit-sd noise: 1/f^χ (row-wise χ) or a Lorentzian peak at `peak` Hz (row-wise)."""
    spec = np.fft.rfft(rng.standard_normal((n, N)), axis=-1)
    f = np.fft.rfftfreq(N, 1 / fs); f[0] = f[1]
    if chi is not None:
        spec = spec / f[None, :] ** (np.asarray(chi, float)[:, None] / 2)
    if peak is not None:
        bw_ = np.broadcast_to(np.asarray(bw, float), (n,))[:, None]
        spec = spec / np.sqrt((f[None, :] - np.asarray(peak, float)[:, None]) ** 2 + bw_ ** 2)
    return zs(np.fft.irfft(spec, N, axis=-1))


