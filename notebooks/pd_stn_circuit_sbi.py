# * Contacts and bands as in diagnostic 2: HFO-best pair; β peak ± 3 Hz; HFO peak ± 40 Hz (pooled OFF+ON).
# * Masks: gentle EMG mask **and** transient rejection (|LFP| or HFO envelope > median + 6 MAD, ± 100 ms).
# * Two nulls: (1) circular shifts; (2) **cross-session surrogate**: β phase from this session paired with HFO
