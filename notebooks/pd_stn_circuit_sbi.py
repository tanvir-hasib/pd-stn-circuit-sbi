def perturb(th_off, hyp, rng):
    th = th_off.copy(); n = len(th); u = lambda a, b: a + (b - a) * rng.random(n)
    if hyp in ("H_GS", "H_GS_HFO"):
        th[:, IX["w_GS"]] *= u(0.3, 0.8)
    if hyp in ("H_SLOW", "H_SLOW_HFO"):
        th[:, IX["sig_slow"]] *= u(0.2, 0.7)
    if hyp in ("H_NOISE", "H_NOISE_HFO"):
        th[:, IX["log10_sig"]] += np.log10(u(0.5, 0.8))
    if hyp == "H_HD":
        th[:, IX["w_CS"]] *= u(0.2, 0.7)
    if hyp == "H_TC":
        th[:, IX["w_TC"]] *= u(0.2, 0.7)
    if hyp in ("H_HFO", "H_GS_HFO", "H_SLOW_HFO", "H_NOISE_HFO"):
        th[:, IX["f_H"]] += u(20, 80); th[:, IX["log10_aH"]] += np.log10(u(1.2, 2.5))
    if hyp == "H_lock":
        th[:, IX["lam_H"]] *= u(0.1, 0.6)
    if hyp == "H_ctx":
        th[:, IX["g_ctx"]] *= u(0.5, 0.85)
    th[:, IX["snr_S"]] += rng.normal(0, 1.5, n); th[:, IX["snr_C"]] += rng.normal(0, 1.5, n)
    # session nuisance (all hypotheses): tremor / θ–α and α change between real sessions too
    th[:, IX["f_T"]] += rng.normal(0, 1.0, n); th[:, IX["bw_T"]] *= np.exp(rng.normal(0, 0.3, n))
    th[:, IX["w_TS"]] *= np.exp(rng.normal(0, 0.4, n)); th[:, IX["w_TM"]] *= np.exp(rng.normal(0, 0.4, n))
    th[:, IX["f_a"]] += rng.normal(0, 0.5, n); th[:, IX["w_a"]] *= np.exp(rng.normal(0, 0.2, n))
    return np.clip(th, PRIOR_LO, PRIOR_HI)


def pair_features(S_off, S_on):
    return np.column_stack([S_off, S_on - S_off])


def pair_bank(n_per, seed):
    fn = OUT_DIR / f"pairs_{n_per}_{config_hash()}_{HYP_TAG}.npz"
    if fn.exists():
        d = np.load(fn); print(f"loaded {fn.name}"); return d["F"], d["y"]
    rng = np.random.default_rng(seed)
    TH_OFF, TH_ON, y = [], [], []
    for h, hyp in enumerate(HYPS):
        th_off = sample_prior(n_per, rng); TH_OFF.append(th_off); TH_ON.append(perturb(th_off, hyp, rng)); y.append(np.full(n_per, h))
    TH_OFF, TH_ON, y = map(np.concatenate, (TH_OFF, TH_ON, y))
    t0 = time.time()
    S_off = simulate_stats(TH_OFF, seed); print(f"  pairs OFF ({(time.time() - t0) / 60:.1f} min)")
    S_on = simulate_stats(TH_ON, seed + 500_000); print(f"  pairs ON ({(time.time() - t0) / 60:.1f} min)")
