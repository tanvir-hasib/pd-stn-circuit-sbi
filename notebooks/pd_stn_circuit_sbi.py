def _F(x, M, B):
    return M / (1.0 + ((M - B) / B) * torch.exp(-4.0 * x / M))


def simulate_circuit(theta, T, dt=None, integrator=None, rec_dt=1e-3, seed=0, device=None, dtype=None,
                     use_graph=None, verbose=False):
    """theta: dict of (n,) arrays for SIM_KEYS. Returns dict uS, uE, S, E → (n, n_rec) float32 at 1/rec_dt.
    uS/uE are the summed synaptic inputs to STN/cortex (LFP/MEG field proxies); S/E are firing rates."""
    c = CIRC
    dt = DT if dt is None else dt
    integrator = INTEGRATOR if integrator is None else integrator
    device = DEVICE if device is None else device
    dtype = DTYPE if dtype is None else dtype
    if use_graph is None:
        use_graph = device.type == "cuda" and USE_CUDA_GRAPH
    th = {k: torch.as_tensor(np.asarray(theta[k], float), dtype=dtype, device=device) for k in SIM_KEYS}
    n = th["w_GS"].numel()
    K = c["K"]
    Y = torch.zeros((20, n), dtype=dtype, device=device)      # row 19 = slow gain fluctuation U
    Y[0] = c["B_S"]; Y[1] = c["B_G"]; Y[2] = c["B_E"]; Y[3] = c["B_I"]
    for name, (src, r0) in CHAINS.items():
        Y[r0:r0 + K] = Y[src]
    kr = {name: (K / c["d_" + name]) / (th["k_d"] if name in BG_CHAINS else 1.0) for name in CHAINS}
    w_IE, w_EI = c["w_IE"] * th["g_ctx"], c["w_EI"] * th["g_ctx"]
    tau_S, tau_G = c["tau_S"] * th["k_d"], c["tau_G"] * th["k_d"]       # k_d scales BG time constants too
    gn = torch.stack([th["sig"] / tau_S, th["sig"] / tau_G, th["sig"] / c["tau_E"] * torch.ones_like(tau_S),
                      th["sig_slow"] * np.sqrt(2.0 / TAU_SLOW)])  # (4, n): S, G, E, U
    w_GS, w_CS, w_TC = th["w_GS"], th["w_CS"], th["w_TC"]
    acc = torch.zeros((4, n), dtype=dtype, device=device)

    def drift(Y):
        S, G, E, I = Y[0], Y[1], Y[2], Y[3]
        uS = w_CS * (Y[15] - c["B_E"]) - w_GS * torch.exp(Y[19]) * (Y[9] - c["B_G"])
        uG = c["w_SG"] * (Y[6] - c["B_S"]) - c["w_GG"] * (Y[12] - c["B_G"])
        uE = c["w_EE"] * (E - c["B_E"]) - w_IE * (I - c["B_I"]) - w_TC * (Y[18] - c["B_S"])
        uI = w_EI * (E - c["B_E"]) - c["w_II"] * (I - c["B_I"])
        parts = [torch.stack([(_F(uS, c["M_S"], c["B_S"]) - S) / tau_S,
                              (_F(uG, c["M_G"], c["B_G"]) - G) / tau_G,
                              (_F(uE, c["M_E"], c["B_E"]) - E) / c["tau_E"],
                              (_F(uI, c["M_I"], c["B_I"]) - I) / c["tau_I"]])]
        for name, (src, r0) in CHAINS.items():
            inp = torch.stack([Y[src], Y[r0], Y[r0 + 1]])
            parts.append(kr[name] * (inp - Y[r0:r0 + K]))
        parts.append((-Y[19] / TAU_SLOW).unsqueeze(0))
        return torch.cat(parts, 0), uS, uE

    def step(dW):
        dY1, uS, uE = drift(Y)
        if integrator == "euler":
            Yn = Y + dt * dY1
        else:
            Yp = Y + dt * dY1
            Yp[0:3] += gn[0:3] * dW[0:3]; Yp[19] += gn[3] * dW[3]
            dY2, _, _ = drift(Yp)
            Yn = Y + 0.5 * dt * (dY1 + dY2)
        Yn[0:3] += gn[0:3] * dW[0:3]; Yn[19] += gn[3] * dW[3]
        acc.add_(torch.stack([uS, uE, Y[0], Y[2]]))
        Y.copy_(Yn)

    n_steps = int(round(T / dt)); dec = int(round(rec_dt / dt)); n_rec = n_steps // dec
    R = GRAPH_REC; n_blocks = -(-n_rec // R)
    dWbuf = torch.zeros((R * dec, 4, n), dtype=dtype, device=device)
    rec_buf = torch.zeros((R, 4, n), dtype=torch.float32, device=device)

    def block():
        for r_ in range(R):
            for j in range(dec):
                step(dWbuf[r_ * dec + j])
            rec_buf[r_].copy_(acc / dec); acc.zero_()

    gen = torch.Generator(device=device).manual_seed(int(seed))
    graph = None
    if use_graph:
        snap = [Y.clone(), acc.clone()]
        st = torch.cuda.Stream(device=device); st.wait_stream(torch.cuda.current_stream(device))
        with torch.no_grad(), torch.cuda.stream(st):
            block()
        torch.cuda.current_stream(device).wait_stream(st)
        Y.copy_(snap[0]); acc.copy_(snap[1])
        graph = torch.cuda.CUDAGraph()
        with torch.no_grad(), torch.cuda.graph(graph):
            block()
    out = np.empty((4, n, n_blocks * R), np.float32)
    t0 = time.time(); sq = np.sqrt(dt)
    with torch.no_grad():
        for bi in range(n_blocks):
            dWbuf.copy_(torch.randn((R * dec, 4, n), generator=gen, device=device, dtype=torch.float32).to(dtype) * sq)
            if graph is not None:
                graph.replay()
            else:
                block()
            out[:, :, bi * R:(bi + 1) * R] = rec_buf.permute(1, 2, 0).cpu().numpy()
            if verbose and (bi + 1) * 10 // n_blocks > bi * 10 // n_blocks:
                print(f"\r  {n} sims: {100 * (bi + 1) / n_blocks:5.1f}%  ({time.time() - t0:5.0f} s)", end="", flush=True)
    if verbose:
        print()
    del graph
    return {k: out[i, :, :n_rec] for i, k in enumerate(("uS", "uE", "S", "E"))}


