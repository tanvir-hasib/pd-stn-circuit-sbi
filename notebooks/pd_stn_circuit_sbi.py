def hedges_paired(a, b):
    d = a - b; n = len(d)
    return d.mean() / ((a.std(ddof=1) + b.std(ddof=1)) / 2) * (1 - 3 / (4 * (n - 1) - 1))


def paired_table(df, metrics, label):
    off = df[df.med == "MedOff"].set_index(["subject", "side"]); on = df[df.med == "MedOn"].set_index(["subject", "side"])
    idx = off.index.intersection(on.index); rows = []
    for m in metrics:
        a, b = off.loc[idx, m].astype(float).values, on.loc[idx, m].astype(float).values
        ok = np.isfinite(a) & np.isfinite(b); a, b = a[ok], b[ok]
        r = dict(metric=m, n=len(a), off=np.mean(a) if len(a) else np.nan, on=np.mean(b) if len(b) else np.nan)
        if len(a) > 4:
            r.update(p_wilcoxon=stats.wilcoxon(a, b).pvalue, g_off_on=hedges_paired(a, b))
        rows.append(r)
    T = pd.DataFrame(rows); print(f"[{label}]"); print(T.round(3).to_string(index=False)); return T


