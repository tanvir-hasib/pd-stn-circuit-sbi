def _mcls(obj):
    c = obj.attrs.get("MATLAB_class", b"")
    return c.decode() if isinstance(c, bytes) else str(c)


def h5_value(f, obj):
    """MATLAB v7.3 → Python: struct group → dict of h5 objects; cell/refs → list; char → str or list of str; numeric → array."""
    if isinstance(obj, h5py.Group):
        return {k: obj[k] for k in obj.keys()}
    if obj.dtype == h5py.ref_dtype or _mcls(obj) == "cell":
        return [h5_value(f, f[r]) for r in np.asarray(obj[()]).ravel()]
    if _mcls(obj) == "char":
        a = np.asarray(obj[()])
        if a.ndim == 2 and min(a.shape) > 1:                      # char matrix: one string per MATLAB row
            return ["".join(chr(c) for c in a[:, i] if c).strip() for i in range(a.shape[1])]
        return "".join(chr(c) for c in a.ravel() if c).strip()
    return np.asarray(obj[()])


def h5_tree(g, prefix="  ", depth=0, max_depth=2):
    for k in g.keys():
        o = g[k]
        if isinstance(o, h5py.Group):
            print(f"{prefix}{k}/ (group{', ' + _mcls(o) if _mcls(o) else ''})")
            if depth < max_depth:
                h5_tree(o, prefix + "  ", depth + 1, max_depth)
        else:
            print(f"{prefix}{k}: shape {o.shape}, {o.dtype}, {_mcls(o) or '-'}")


def _as_strings(v):
    if isinstance(v, str):
        return [v]
    if isinstance(v, list) and v and all(isinstance(x, str) for x in v):
        return v
    if isinstance(v, list) and v and all(isinstance(x, list) for x in v):
        return [x[0] if x and isinstance(x[0], str) else str(x) for x in v]
    return None


