# ## 10.7 Full joint network and β-reachability analysis
#
# **Why.** In v4.6 the joint posterior did not reproduce the observed β reduction (posterior predictive Δβ ≈ 0
# vs observed −0.064). Two explanations: (1) the check mixed the joint posterior (11 OFF parameters) with the
# separate single-session fits for the other 12, which need not be consistent; (2) the model cannot make the
# β drop the way the data show it. This section separates them, without new bank simulations.
#
# **(A) Full joint network:** same joint simulations, but the posterior now covers all 25 OFF parameters, the
# 11 candidate changes **and** the 8 session-nuisance changes (SNR, low-frequency component, α). The posterior
# predictive check is then drawn from this one posterior: OFF match, ON match, OFF→ON change, and an
# **ablation** (same draws with the 11 candidate changes set to zero) to show how much of the predicted change
# is carried by the mechanism rather than by session nuisance.
#
# **(B) β reachability:** for each hemisphere, the 300 joint simulations whose OFF statistics are closest to
# that hemisphere's OFF data. Within them: how often a β drop as large as observed occurs; which parameter
# changes produce it (drop-one R² of a linear model of Δβ on all changes; mean change in the pairs that reach
# the observed drop); and whether the *other* OFF→ON changes that accompany such a β drop in the model
# (β frequency, bursts, coherence, delay, HFO) match the data, i.e. whether the data's β drop carries the
# model's signature.

