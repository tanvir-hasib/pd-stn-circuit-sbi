JNUIS = {"snr_S": "add", "snr_C": "add", "f_T": "add", "bw_T": "log", "w_TS": "log", "w_TM": "log", "f_a": "add", "w_a": "log"}
JNP = list(JNUIS); JNIX = [IX[p] for p in JNP]


def nuis_delta(th_off, th_on):
    return np.column_stack([np.log(np.maximum(th_on[:, IX[p]], 1e-9) / np.maximum(th_off[:, IX[p]], 1e-9)) if JNUIS[p] == "log"
                            else th_on[:, IX[p]] - th_off[:, IX[p]] for p in JNP])


def apply_full(th_off, Dm, Dn):
    th = apply_delta(th_off, Dm)
    for k, p in enumerate(JNP):
        j = IX[p]; th[:, j] = th[:, j] * np.exp(Dn[:, k]) if JNUIS[p] == "log" else th[:, j] + Dn[:, k]
    return np.clip(th, PRIOR_LO, PRIOR_HI)


def bounded_samples(post, x, lo, hi, n=2000, max_draws=200_000, chunk=20_000):
    xt = torch.tensor(np.asarray(x, float), dtype=torch.float32); keep, drawn = [], 0
    while drawn < max_draws:
        m = min(chunk, max_draws - drawn) if drawn else max(n, 2000)
        s = post.sample((m,), x=xt, show_progress_bars=False, reject_outside_prior=False).detach().cpu().numpy(); drawn += m
        keep.append(s[((s >= lo) & (s <= hi)).all(1)])
        if sum(len(k) for k in keep) >= n:
            break
    inside = np.concatenate(keep)
    return inside[:n] if len(inside) >= 50 else np.clip(s[:n], lo, hi)


def make_npe_bounded(phi, F, lo, hi, tag, seed=0):
    fn = OUT_DIR / f"jnpe_{tag}_{len(phi)}_{config_hash()}_{J_TAG}_s{seed}.pt"
