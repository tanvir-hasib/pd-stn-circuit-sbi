def side_filter(titles, idx, side):
    """If LFP titles carry explicit left/right tags for both sides, keep the channels of the file's side."""
    tag = lambda t: ("left" if re.search(r"(?i)^(l|le|lt|left)\d|(^|[^a-z])(l|le|left|lstn)([^a-z]|$)|stn_?l", t)
                     else "right" if re.search(r"(?i)^(r|ri|rt|right)\d|(^|[^a-z])(r|ri|right|rstn)([^a-z]|$)|stn_?r", t) else None)
    tags = {i: tag(titles[i]) for i in idx}
    if side in ("left", "right") and side in set(tags.values()):
        return [i for i in idx if tags[i] == side]
