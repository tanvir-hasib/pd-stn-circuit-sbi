def notch_freqs(fs):
    lf = PIPE["line_freq"]
    return [lf * k for k in range(1, int(450 // lf) + 1) if lf * k < fs / 2] + [h for h in PIPE["hpi_freqs"] if h < fs / 2]


def apply_notches(x, fs):
    """Same frequencies as the data (50 Hz harmonics, HPI coils), zero-phase, Q = f / 1 Hz."""
    sos = np.concatenate([signal.tf2sos(*signal.iirnotch(f0, f0 / 1.0, fs)) for f0 in notch_freqs(fs)])
    return signal.sosfiltfilt(sos, x, axis=-1)


def notch_mask(f, fs, width=2.0):
    m = np.ones_like(f, bool)
    for f0 in notch_freqs(fs):
        m &= np.abs(f - f0) > width
    return m


def _lowpass_c(n, N, fs, rng, bw):
    """Unit-sd complex noise with a Lorentzian spectrum of half-width bw around 0 Hz (HFO carrier envelope)."""
    f = np.fft.fftfreq(N, 1 / fs)
    spec = (rng.standard_normal((n, N)) + 1j * rng.standard_normal((n, N))) / np.sqrt((f[None, :]) ** 2 + bw ** 2)
    z = np.fft.ifft(spec, axis=-1)
    return z / np.sqrt((np.abs(z) ** 2).mean(-1, keepdims=True) / 2 + 1e-24)     # Re(z·e^{iφ}) has unit sd


def beta_state(uS_c, fs):
    """Slow β state E_β(t) = 0.5-s smoothed |Hilbert(β-band u_S)| / B_REF (rows of uS_c, mean-removed u_S)."""
    from scipy.ndimage import uniform_filter1d
    sos = signal.butter(4, PIPE["beta"], btype="band", fs=fs, output="sos")
    env = np.abs(signal.hilbert(signal.sosfiltfilt(sos, uS_c, axis=-1), axis=-1))
    env = uniform_filter1d(env, int(0.5 * fs), axis=-1, mode="nearest")
    return np.maximum(env / B_REF, 1e-3)


def stn_hfo(uS_c, S, th, rng, fs, chunk=128, lnEb_const=None):
    """v5 circuit-gated STN HFO (unit = U_REF_S). The slow β state of the STN input,
    E_β(t) = (0.5-s smoothed |Hilbert(β-band u_S)|) / B_REF, gates the HFO:
      amplitude  a_H · E_β^(−κ_H) · (1 + λ_H·tanh z(S))       (β-state suppression + fast β-phase locking via S)
      frequency  f_H − ν_H · ln E_β   (clipped to 150–470 Hz)  (slow HFO in high-β states, fast HFO in low-β states)
    so a circuit change that lowers β raises HFO power and frequency without any change of a_H or f_H.
    lnEb_const (v5.1 ablation): per-row constant ln E_β replacing E_β(t), i.e. the gate is frozen."""
    n, N = uS_c.shape; out = np.empty((n, N))
    for i in range(0, n, chunk):
        sl = slice(i, i + chunk); m = min(chunk, n - i)
        Eb = (beta_state(uS_c[sl], fs) if lnEb_const is None
              else np.broadcast_to(np.exp(np.asarray(lnEb_const, float)[sl])[:, None], (m, N)))
        k_, nu_ = th[sl, IX["kappa_H"]][:, None], th[sl, IX["nu_H"]][:, None]
        f_inst = np.clip(th[sl, IX["f_H"]][:, None] - nu_ * np.log(Eb), *HFO_F_LIM)
        phi = 2 * np.pi * np.cumsum(f_inst, -1) / fs
        car = np.real(_lowpass_c(m, N, fs, rng, HFO_BW) * np.exp(1j * phi))
        out[sl] = (10 ** th[sl, IX["log10_aH"]][:, None]) * Eb ** (-k_) * (1.0 + th[sl, IX["lam_H"]][:, None] * np.tanh(zs(S[sl]))) * car
    return out


def observe(rec, th, rng, fs=None, drop=None, lnEb_const=None):
    """Recorded traces (dict of (n, N)) + θ → (lfp, meg) at fs, burn-in dropped.
    v5: ABSOLUTE scale. The circuit fields are divided by fixed reference amplitudes (not z-scored), and the
    aperiodic background, HFO and low-frequency component have fixed absolute sizes, so a circuit change that
    weakens β lowers β power relative to the background — as levodopa does — instead of being normalised away."""
    fs = PIPE["fs"] if fs is None else fs
    th = np.atleast_2d(th)
    d0 = int((2.0 if drop is None else drop) * fs)
    uS, uE, S, E = (rec[k][:, d0:].astype(float) for k in ("uS", "uE", "S", "E"))
    n, N = uS.shape
    uS_c = uS - uS.mean(-1, keepdims=True); uE_c = uE - uE.mean(-1, keepdims=True)
    hE = zs(np.sqrt(np.clip(E, 0, None)) * rng.standard_normal((n, N)))
    g = lambda k: th[:, IX[k]][:, None]
    lfp = uS_c / U_REF_S + stn_hfo(uS_c, S, th, rng, fs, lnEb_const=lnEb_const)
    meg = uE_c / U_REF_E + g("w_a") * shaped_noise(n, N, fs, rng, peak=th[:, IX["f_a"]]) + 10 ** g("log10_gC") * hE
    trem = shaped_noise(n, N, fs, rng, peak=th[:, IX["f_T"]], bw=th[:, IX["bw_T"]])   # tremor / θ–α, shared by both sites
    lfp = lfp + g("w_TS") * trem; meg = meg + g("w_TM") * trem
    bgS = 10 ** (-g("snr_S") / 20); bgC = 10 ** (-g("snr_C") / 20)        # background sd in reference units
    lfp = lfp + shaped_noise(n, N, fs, rng, chi=th[:, IX["chi_S"]]) * bgS
    meg = meg + shaped_noise(n, N, fs, rng, chi=th[:, IX["chi_C"]]) * bgC
    # white sensor/amplifier floor relative to the background, then the same notches as the recorded data
    lfp = lfp + 10 ** g("log10_flS") * bgS * rng.standard_normal((n, N))
    meg = meg + 10 ** g("log10_flC") * bgC * rng.standard_normal((n, N))
    return apply_notches(lfp, fs).astype(np.float32), apply_notches(meg, fs).astype(np.float32)


def aperiodic_fit(f, P, lo, hi, n_iter=2, keep_q=0.6, fs=None):
    m = (f >= lo) & (f <= hi) & notch_mask(f, PIPE["fs"] if fs is None else fs)
    lf, lp = np.log10(f[m]), np.log10(P[..., m])
    w = np.ones_like(lp)
    for _ in range(n_iter + 1):
        sw = w.sum(-1, keepdims=True)
        mx = (w * lf).sum(-1, keepdims=True) / sw; my = (w * lp).sum(-1, keepdims=True) / sw
        slope = (w * (lf - mx) * (lp - my)).sum(-1) / (w * (lf - mx) ** 2).sum(-1)
        off = my[..., 0] - slope * mx[..., 0]
        res = lp - (off[..., None] + slope[..., None] * lf)
        w = (res <= np.quantile(res, keep_q, axis=-1, keepdims=True)).astype(float)
    return -slope, off


def phase_amp(x, pband, aband, fs):
    e = int(PIPE["edge_trim"] * fs)
    ph = np.angle(signal.hilbert(bandpass(x, *pband, fs), axis=-1))[..., e:-e]
    am = np.abs(signal.hilbert(bandpass(x, *aband, fs), axis=-1))[..., e:-e]
    return ph, am


def draw_shifts(N, fs, seed=7):
    ms = int(PIPE["min_shift"] * fs)
    return np.random.default_rng(seed).integers(ms, N - ms, PIPE["n_surr"])


def pac_masked(ph, am, w, shifts):
    """Masked MVL: samples with w = 0 (EMG bursts) contribute nothing. z vs circular shifts,
    normalised MVL, preferred phase, Tort MI. ph, am, w: (n, N)."""
    N = ph.shape[-1]
    a = np.fft.fft(w * np.exp(1j * ph), axis=-1); b = np.fft.fft(w * am, axis=-1)
    cc = np.fft.ifft(a * np.conj(b), axis=-1)
    W = np.fft.fft(w, axis=-1)
    cnt = np.maximum(np.real(np.fft.ifft(W * np.conj(W), axis=-1)), 1.0)
    mv = np.abs(cc) / cnt
    z = (mv[:, 0] - mv[:, shifts].mean(-1)) / mv[:, shifts].std(-1)
    nmvl = mv[:, 0] / ((w * am).sum(-1) / w.sum(-1))
    nb = 18
    idx = np.clip(((ph + np.pi) / (2 * np.pi) * nb).astype(int), 0, nb - 1)
    means = np.stack([((idx == k) * w * am).sum(-1) / np.maximum(((idx == k) * w).sum(-1), 1) for k in range(nb)], -1)
    Pm = means / means.sum(-1, keepdims=True)
    tort = (np.log(nb) + (Pm * np.log(Pm + 1e-300)).sum(-1)) / np.log(nb)
    return z, np.log(nmvl), np.cos(np.angle(cc[:, 0])), np.sin(np.angle(cc[:, 0])), np.log10(tort + 1e-12)


def burst_stats(env, fs):
    thr = np.percentile(env, PIPE["burst_pct"], axis=-1, keepdims=True)
    above = env > thr
    rate, dur = np.zeros(len(env)), np.zeros(len(env))
    for i, a in enumerate(above):
        d = np.diff(np.concatenate([[0], a.astype(np.int8), [0]]))
        L = (np.where(d == -1)[0] - np.where(d == 1)[0]) / fs
        L = L[L >= 0.05]
        rate[i] = len(L) / (env.shape[-1] / fs); dur[i] = L.mean() if len(L) else 0.0
    return rate, dur, above


def waveform_shape(bb, nb, above, fs):
    w = max(1, int(round(fs / 80))); d = max(1, int(round(0.005 * fs))); off = np.arange(-w, w + 1)
    out_s, out_r = np.full(len(bb), np.nan), np.full(len(bb), np.nan)
    for i in range(len(bb)):
        x, y = bb[i], nb[i]
        pk = np.where((y[1:-1] > y[:-2]) & (y[1:-1] >= y[2:]))[0] + 1
        tr = np.where((y[1:-1] < y[:-2]) & (y[1:-1] <= y[2:]))[0] + 1
        lo, hi = w + d, len(x) - w - d - 1
        pk = pk[(pk > lo) & (pk < hi)]; tr = tr[(tr > lo) & (tr < hi)]
        pk = pk[above[i, pk]]; tr = tr[above[i, tr]]
        if len(pk) < 10 or len(tr) < 10:
            continue
        pk = pk + off[np.argmax(x[pk[:, None] + off], axis=1)]
        tr = np.unique(tr + off[np.argmin(x[tr[:, None] + off], axis=1)])
        sp = 0.5 * (np.abs(x[pk] - x[pk - d]) + np.abs(x[pk] - x[pk + d]))
        st = 0.5 * (np.abs(x[tr] - x[tr - d]) + np.abs(x[tr] - x[tr + d]))
        out_s[i] = np.log(sp.mean() / st.mean())
        j = np.searchsorted(tr, pk); ok = (j > 0) & (j < len(tr))
        rise = (pk[ok] - tr[j[ok] - 1]) / fs; decay = (tr[j[ok]] - pk[ok]) / fs
        good = (rise + decay) < 1.5 / 13.0
        if good.sum() > 5:
            out_r[i] = np.mean(rise[good] / (rise[good] + decay[good]))
    return out_s, out_r


SITE_STATS = ["ap_exp", "mid_slope", "floor_lvl", "theta_res", "lf_pk_f", "alpha_res", "beta_res", "beta_pk_f", "beta_pk_h",
              "burst_rate", "burst_dur", "env_cv", "sharp_lr", "rdsym",
              "pac_z", "pac_lnmvl", "pac_cos", "pac_sin", "pac_ltort"]
CROSS_STATS = ["coh_beta", "icoh_beta", "delay_ms", "aec_beta", "xpac_stn2ctx", "xpac_ctx2stn"]
HFO_STATS = ["stn_hfo_excess", "stn_hfo_ratio", "stn_hfo_peak_f"]
STAT_NAMES = [f"stn_{s}" for s in SITE_STATS] + [f"meg_{s}" for s in SITE_STATS] + CROSS_STATS + HFO_STATS


def robust_cv(env):
    """(q90 − q10) / median of the β envelope: burstiness that brief artefacts cannot dominate."""
    q10, q50, q90 = np.percentile(env, [10, 50, 90], axis=-1)
    return (q90 - q10) / q50


def site_stats(x, hfa_band, fs, w, shifts):
    B = PIPE["beta"]; e = int(PIPE["edge_trim"] * fs)
    f, P = signal.welch(x, fs, nperseg=int(2 * fs), axis=-1)
    ap, off = aperiodic_fit(f, P, 2.0, 45.0)
    mid, _ = aperiodic_fit(f, P, 30.0, 45.0, n_iter=0)
    nmf = notch_mask(f, fs)
    hf = np.log10(P[:, (f >= 430) & (f <= 480) & nmf].mean(-1) / P[:, (f >= 30) & (f <= 45) & nmf].mean(-1))  # floor level
    f1 = f[1:]; nm = notch_mask(f1, fs)
    flat = np.log10(P[:, 1:]) - (off[:, None] - ap[:, None] * np.log10(f1))
    br = lambda lo, hi: flat[:, (f1 >= lo) & (f1 <= hi) & nm].mean(-1)
    mb = (f1 >= 15.0) & (f1 <= B[1]) & nm
    ph_b, am_b = phase_amp(x, B, B, fs)
    ph, am = phase_amp(x, B, hfa_band, fs)
    rate, dur, above = burst_stats(am_b, fs)
    bb = bandpass(x, 1.0, 45.0, fs)[:, e:-e]; nbx = bandpass(x, *B, fs)[:, e:-e]
    sh, rd = waveform_shape(bb, nbx, above, fs)
    pz = pac_masked(ph, am, w, shifts)
    ml = (f1 >= 3.0) & (f1 <= 12.0) & nm
    cols = [ap, mid, hf, br(3.0, 7.0), f1[ml][np.argmax(flat[:, ml], -1)], br(*PIPE["alpha"]), br(*B), f1[mb][np.argmax(flat[:, mb], -1)], flat[:, mb].max(-1),
            rate, dur, robust_cv(am_b), sh, rd, *pz]
    return np.column_stack(cols), ph, am, am_b


def hfo_stats(x, fs):
    """HFO power above a 60–450 Hz 1/f fit (200–420 Hz), fast/slow ratio, smoothed peak frequency."""
    f, P = signal.welch(x, fs, nperseg=int(fs), axis=-1)
    ap, off = aperiodic_fit(f, P, 60.0, 450.0)
    nm = notch_mask(f, fs); f1 = np.maximum(f, f[1])
    flat = np.log10(P) - (off[:, None] - ap[:, None] * np.log10(f1))
    mh = (f >= 200) & (f <= 420) & nm
    excess = flat[:, mh].mean(-1)
    ratio = np.log10(P[:, (f >= 300) & (f <= 400) & nm].mean(-1) / P[:, (f >= 200) & (f <= 290) & nm].mean(-1))
    fl = np.where(mh[None, :], flat, np.nan)
    k = np.ones(21) / 21
    sm = np.array([np.convolve(np.nan_to_num(r, nan=np.nanmean(r)), k, "same") for r in fl])
    peak = f[mh][np.argmax(sm[:, mh], -1)]
    return excess, ratio, peak


def compute_stats_parallel(lfp, meg, chunk=32):
    """compute_stats over CPU processes (simulations only; no masks)."""
    if N_JOBS <= 1 or len(lfp) <= chunk:
        return compute_stats(lfp, meg)
    try:
        from joblib import Parallel, delayed
        parts = Parallel(n_jobs=N_JOBS)(delayed(compute_stats)(lfp[i:i + chunk], meg[i:i + chunk])
                                        for i in range(0, len(lfp), chunk))
        return np.concatenate(parts)
    except Exception as e:
        warnings.warn(f"parallel statistics failed ({e}); running serially")
        return compute_stats(lfp, meg)


def compute_stats(lfp, meg, fs=None, w=None, batch=64):
    """(n, N) LFP and MEG → (n, len(STAT_NAMES)). w: optional (n, N) 0/1 mask (EMG bursts)."""
    fs = PIPE["fs"] if fs is None else fs
    lfp, meg = np.atleast_2d(lfp).astype(float), np.atleast_2d(meg).astype(float)
    e = int(PIPE["edge_trim"] * fs)
    Ne = lfp.shape[-1] - 2 * e
    shifts = draw_shifts(Ne, fs)
    W = np.ones((len(lfp), Ne)) if w is None else np.atleast_2d(w)[:, e:-e].astype(float)
    out = []
    for s in range(0, len(lfp), batch):
        a, b, wb = zs(lfp[s:s + batch]), zs(meg[s:s + batch]), W[s:s + batch]
        Ss, ph_s, am_s, env_s = site_stats(a, PIPE["hfa_stn"], fs, wb, shifts)
        Sm, ph_m, am_m, env_m = site_stats(b, PIPE["hfa_ctx"], fs, wb, shifts)
        f, Cxy = signal.csd(a, b, fs, nperseg=int(fs), axis=-1)
        _, Pxx = signal.welch(a, fs, nperseg=int(fs), axis=-1); _, Pyy = signal.welch(b, fs, nperseg=int(fs), axis=-1)
        mb = (f >= PIPE["beta"][0]) & (f <= PIPE["beta"][1])
        cohc = Cxy / np.sqrt(Pxx * Pyy)
        coh = np.abs(cohc[:, mb]).mean(-1); icoh = np.abs(np.imag(cohc[:, mb])).mean(-1)
        # delay from the β phase slope, weighted by coherence (positive: STN leads cortex)
        phs = np.unwrap(np.angle(Cxy[:, mb]), axis=-1); wt = np.abs(cohc[:, mb]) ** 2
        fm = f[mb][None, :]
        mx = ((wt * fm).sum(-1) / wt.sum(-1))[:, None]; my = ((wt * phs).sum(-1) / wt.sum(-1))[:, None]
        slope = (wt * (fm - mx) * (phs - my)).sum(-1) / (wt * (fm - mx) ** 2).sum(-1)
        delay = -1e3 * slope / (2 * np.pi)      # csd phase = φ_MEG − φ_STN; verified: STN leading by 10 ms → +10.5 ms
        ea, eb = zs(env_s), zs(env_m); aec = (ea * eb).mean(-1)
        x1 = pac_masked(ph_s, am_m, wb, shifts)[0]          # STN β phase → cortical HFA
        x2 = pac_masked(ph_m, am_s, wb, shifts)[0]          # cortical β phase → STN HFA
        out.append(np.column_stack([Ss, Sm, coh, icoh, delay, aec, x1, x2, *hfo_stats(a, fs)]))
    return np.concatenate(out)


