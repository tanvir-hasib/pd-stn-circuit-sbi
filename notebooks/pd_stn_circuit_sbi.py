def make_npe(theta, X, seed=0):
    fn = OUT_DIR / f"npe_{len(theta)}_{config_hash()}_s{seed}.pt"
    if fn.exists():
        print(f"loaded {fn.name}")
        return torch.load(fn, weights_only=False)
    post = _make_npe(theta, X, seed)
    try:
        torch.save(post, fn)
    except Exception as e:
        warnings.warn(f"could not cache the posterior ({e})")
    return post


def _make_npe(theta, X, seed=0):
    from sbi.utils import BoxUniform
    try:
        from sbi.inference import NPE
    except ImportError:
        from sbi.inference import SNPE as NPE
    torch.manual_seed(seed)
    good = np.isfinite(X).all(1)
    prior = BoxUniform(torch.tensor(PRIOR_LO, dtype=torch.float32), torch.tensor(PRIOR_HI, dtype=torch.float32))
    inf = NPE(prior=prior, density_estimator="nsf")
    inf.append_simulations(torch.tensor(theta[good], dtype=torch.float32), torch.tensor(X[good], dtype=torch.float32))
    return inf.build_posterior(inf.train(show_train_summary=False))


def post_samples(posterior, x, n=1000, return_frac=False, max_draws=400_000, chunk=20_000):
    """Rejection sampling, as sbi does by default: draw from the flow until n in-prior samples are collected
    (or max_draws). frac = in-prior fraction, reported as a diagnostic of leakage."""
    xt = torch.tensor(np.asarray(x, float), dtype=torch.float32)
    keep, drawn = [], 0
    while drawn < max_draws:
        m = min(chunk, max_draws - drawn) if drawn else max(n, 2000)
        s = posterior.sample((m,), x=xt, show_progress_bars=False, reject_outside_prior=False).detach().cpu().numpy()
        drawn += m
        keep.append(s[((s >= PRIOR_LO) & (s <= PRIOR_HI)).all(1)])
        if sum(len(k) for k in keep) >= n:
            break
    inside = np.concatenate(keep); frac = len(inside) / drawn
    s = inside[:n] if len(inside) >= 50 else np.clip(s[:n], PRIOR_LO, PRIOR_HI)
    return (s, frac) if return_frac else s


