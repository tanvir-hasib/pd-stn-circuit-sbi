def build_manifest(root):
    rows = []
    for f in sorted(Path(root).glob("sub-*/ses-*/meg/*_meg.fif")):
        name = f.name
        if "task-noise" in name:
            continue
        ent = dict(re.findall(r"(sub|ses|task|acq|run|split)-([A-Za-z0-9]+)", name))
        if ent.get("split", "01") != "01" or "acq" not in ent:
            continue
        rows.append(dict(subject=ent["sub"], session=ent.get("ses"), task=ent["task"], med=ent["acq"],
                         run=int(ent.get("run", 1)), path=str(f)))
    df = pd.DataFrame(rows)
